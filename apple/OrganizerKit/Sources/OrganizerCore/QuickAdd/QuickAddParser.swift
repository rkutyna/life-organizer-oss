// Quick-add: reads one line typed into the reminders quick-add box ("Call the plumber tomorrow 3pm !1") and
// returns a title, a due day and time, a priority, and the words that named the day.
//
// Supported phrases (case-insensitive; date_text keeps the typed casing):
//   Days:       today, tonight, tomorrow, the day after tomorrow; a weekday (full or short name),
//               optionally after "on", "this" or "next" ("next" is the first such weekday after
//               today, so "next friday" on a Friday is a week away); in N days/weeks/months/years;
//               next week, next month, next year; "Oct 30", "Oct 30th", "30 oct", "Oct 30 2027";
//               "10/28", "12/5", "12/5/2027", "2026-12-20". A day without a year rolls forward to
//               next year once it has passed.
//   Hours:      3pm, 8 pm, 3:30pm, 14:00, "at 9:30", "at 1", noon, midnight, in N minutes/hours
//               (these two are relative to now and carry a date too).
//   Times of day: morning, afternoon, evening, night (and "this" + one of them, which means today).
//               They set a day but no due_time, because their hour is not certain.
//   Merges:     a day and an hour next to each other are one phrase: "tomorrow 3pm", "today at noon",
//               "sat 11am", "10/28 at 3:30pm", "at 3pm tomorrow", "sunday night".
//   Bare hours: with no day, the hour is today, or tomorrow once it has passed ("Standup at 9:30"
//               at 10:30 is tomorrow).
//   Priority:   "!1", "!2" or "!3" standing alone (start of text or after a space, then a space or
//               the end). Only the first one counts, and it is removed from the title.
//
// The first date-ish phrase in the text is the one used; the rest stays in the title, minus a
// dangling "on", "at", "by", "due", "for" or "from" left at the end.
//
// The golden file (apple/OrganizerKit/Tests/OrganizerCoreTests/Fixtures/quickadd-golden.json) is the spec. It is generated by
// apple/scripts/quickadd-golden.mjs from the web parser (web/src/modules/reminders/parse.ts, chrono-node
// with forwardDate). Where chrono does something odd, a golden case shows it and the code mirrors it:
// "Morning run 6am" reads "Morning" as the phrase (title "run 6am", due tomorrow, no time), and
// "Leave at midnight" keeps "midnight" but not "at" in the date text.

import Foundation
import OrganizerAPI

/// What one line of quick-add text means: "Call the plumber tomorrow 3pm !1" ->
/// title "Call the plumber", due 2026-10-24 15:00, priority 1.
nonisolated public struct QuickAdd: Equatable, Sendable {
    public var title: String
    public var dueDate: LocalDate?
    /// Only when the text named an hour ("3pm", "at 9:30", "noon", "in 2 hours").
    public var dueTime: LocalTime?
    /// 1 high, 2 medium, 3 low, from "!1" / "!2" / "!3".
    public var priority: Int?
    /// The words read as the date, exactly as typed ("tomorrow 3pm"), for highlighting.
    public var dateText: String?

    public init(title: String, dueDate: LocalDate? = nil, dueTime: LocalTime? = nil, priority: Int? = nil, dateText: String? = nil) {
        self.title = title
        self.dueDate = dueDate
        self.dueTime = dueTime
        self.priority = priority
        self.dateText = dateText
    }
}

/// The port of web/src/modules/reminders/parse.ts (chrono-node with forwardDate).
nonisolated public enum QuickAddParser {
    public static func parse(_ input: String, now: Date = Date(), calendar: Calendar = .current) -> QuickAdd {
        let reference = QuickAddReference(now: now, calendar: calendar)
        var text = input
        var priority: Int?
        if let flag = priorityFlag(in: text) {
            priority = flag.value
            text.replaceSubrange(flag.range, with: " ")
        }
        guard let match = QuickAddMatching.firstMatch(in: text, reference: reference) else {
            return QuickAdd(title: tidy(text), priority: priority)
        }
        let before = String(text[..<match.range.lowerBound])
        let after = String(text[match.range.upperBound...])
        let rest = tidy(before + " " + after)
        return QuickAdd(
            title: rest.isEmpty ? tidy(text) : rest,
            dueDate: match.day,
            dueTime: match.time,
            priority: priority,
            dateText: String(text[match.range])
        )
    }

    /// The first standalone "!1", "!2" or "!3" and its digit. Matches the web's PRIORITY pattern.
    private static func priorityFlag(in text: String) -> (range: Range<String.Index>, value: Int)? {
        guard let match = QuickAddPattern(#"(^|\s)!([123])(?=\s|$)"#).matches(in: text).first,
              let value = match.group(2).flatMap({ Int($0) })
        else { return nil }
        return (match.range, value)
    }

    /// The web's tidy(): collapse whitespace, trim, then drop one dangling connector word at the end.
    static func tidy(_ text: String) -> String {
        let collapsed = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        guard let dangling = QuickAddPattern(#"\s+(on|at|by|due|for|from)$"#).matches(in: collapsed).first else {
            return collapsed
        }
        return String(collapsed[..<dangling.range.lowerBound]).trimmingCharacters(in: .whitespaces)
    }
}
