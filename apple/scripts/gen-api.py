#!/usr/bin/env python3
"""Generate the native apps' API types from the server's OpenAPI schema.

The native twin of the web's `npm run gen:api`. Reads apple/OrganizerKit/openapi.json (the
committed snapshot; `gen-api.sh` refreshes it from a running server) and writes:

  apple/OrganizerKit/Sources/OrganizerAPI/Generated/Models.swift      components.schemas
  apple/OrganizerKit/Sources/OrganizerAPI/Generated/Operations.swift  one function per operation

Never edit those files by hand. Change the server, then run apple/scripts/gen-api.sh.

Why a small generator and not swift-openapi-generator: version 1.9.0 was tried on this schema. It
drops every nullable property (FastAPI writes `T | None` as `anyOf: [T, {type: null}]`, which it
skips as an unsupported "null" schema), so every nullable field (a reminder's due date, every field of an update body)
vanished, and it cannot send an explicit null, which PATCH needs to clear a field.

Mapping (see apple/README.md, "API types"):
  string                -> String          integer -> Int        number -> Double
  string/date           -> LocalDate       string/time -> LocalTime   string/date-time -> Date
  boolean               -> Bool            array -> [T]          object with additionalProperties -> [String: T]
  string enum           -> nested open enum (unknown values decode to .unknown("raw"))
  anyOf [T, null]       -> T?              anything else untyped or mixed -> JSONValue
Request bodies: a property that is optional and nullable is an `Omittable<T>`: .omitted (left out,
the default), .null (sent as null: clears the field) or .value(x).
Operations are grouped by OpenAPI tag: `API.Reminders.listReminders(...)` returns an
`Endpoint<[ReminderOut]>` that `OrganizerClient.send` runs.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # apple/
SPEC = ROOT / "OrganizerKit" / "openapi.json"
OUT = ROOT / "OrganizerKit" / "Sources" / "OrganizerAPI" / "Generated"

HEADER = """\
// GENERATED by apple/scripts/gen-api.py from apple/OrganizerKit/openapi.json. Do not edit.
// Regenerate with apple/scripts/gen-api.sh [base_url] after the server's API changes.
"""

# Reserved words that need backticks as identifiers (contextual ones like `open` do not).
SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "func", "import", "init", "inout",
    "let", "operator", "precedencegroup", "protocol", "rethrows", "struct", "subscript",
    "typealias", "var", "break", "case", "catch", "continue", "default", "defer", "do", "else",
    "fallthrough", "for", "guard", "if", "in", "repeat", "return", "throw", "switch", "where",
    "while", "as", "false", "is", "nil", "self", "Self", "super", "throws", "true", "try",
    "private", "public", "internal", "fileprivate", "static",
}
# Names a generated top-level type must not take: they would shadow Swift, Foundation or
# SwiftUI types in feature code that imports both. A schema with one of these names is
# generated as "API<Name>" (and the generator says so).
RESERVED_TYPE_NAMES = {
    "Task", "Date", "Data", "URL", "Error", "Result", "Set", "Calendar", "Locale", "TimeZone",
    "Color", "Text", "Label", "Link", "Section", "Group", "Tab", "Image", "Button", "List",
    "Form", "Toggle", "Picker", "Menu", "View", "Scene", "App", "Window", "Notification",
    "Timer", "Range", "Character", "String", "Int", "Bool", "Double", "Array", "Dictionary",
    "Optional", "Never", "Void", "Codable", "Hashable", "Identifiable", "Duration", "Measurement",
    "JSONValue", "LocalDate", "LocalTime", "Omittable", "Endpoint", "API", "NoContent", "APIError",
    "OpenEnum", "QueryValue", "HTTPMethod", "Type", "Protocol",
}


# --------------------------------------------------------------------------- naming


def camel(name: str, upper: bool = False) -> str:
    """snake_case / kebab-case / "Title Case" -> camelCase (or UpperCamelCase)."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", name) if p]
    if not parts:
        return "value"
    out = []
    for i, part in enumerate(parts):
        if i == 0 and not upper:
            # Keep an all-caps leading word lowercase ("URL" -> "url"), else lower its first char.
            out.append(part.lower() if part.isupper() else part[0].lower() + part[1:])
        else:
            out.append(part[0].upper() + part[1:])
    result = "".join(out)
    if result[0].isdigit():
        result = "_" + result
    return result


def ident(name: str) -> str:
    """A Swift identifier for a property or parameter, escaped when it is a keyword."""
    value = camel(name)
    return f"`{value}`" if value in SWIFT_KEYWORDS else value


def bare(identifier: str) -> str:
    return identifier.strip("`")


def singular(name: str) -> str:
    if name.endswith("ies"):
        return name[:-3] + "y"
    if name.endswith("ses") or name.endswith("xes"):
        return name[:-2]
    if name.endswith("s") and not name.endswith("ss"):
        return name[:-1]
    return name + "Item"


def enum_case(value: str) -> str:
    descending = value.startswith("-")
    name = camel(value.lstrip("-")) + ("Descending" if descending else "")
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = []
    for raw in text.strip().splitlines():
        lines.append(f"{indent}/// {raw.rstrip()}".rstrip())
    return lines


# --------------------------------------------------------------------------- types


@dataclass
class Nested:
    """A type declared inside another one (an inline enum)."""

    name: str
    values: list[str]
    description: str | None = None


@dataclass
class TypeRef:
    swift: str
    nullable: bool = False


@dataclass
class Context:
    spec: dict
    names: dict[str, str]  # schema name -> Swift type name
    request_schemas: set[str]
    notes: list[str] = field(default_factory=list)

    def ref(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        return self.names[name]


def is_null(schema: dict) -> bool:
    return schema.get("type") == "null"


def resolve(schema: dict, ctx: Context, nested_name: str, nested: list[Nested]) -> TypeRef:
    """The Swift type for a schema. Inline enums become nested types named `nested_name`."""
    if not schema:
        return TypeRef("JSONValue")
    if "$ref" in schema:
        return TypeRef(ctx.ref(schema["$ref"]))
    for key in ("anyOf", "oneOf"):
        if key in schema:
            options = schema[key]
            nullable = any(is_null(o) for o in options)
            rest = [o for o in options if not is_null(o)]
            if len(rest) == 1:
                inner = resolve(rest[0], ctx, nested_name, nested)
                return TypeRef(inner.swift, nullable or inner.nullable)
            if rest and all(o.get("type") == "string" and "enum" not in o for o in rest):
                # e.g. CalendarItem.start: a date-time or a date. Left as the raw string.
                return TypeRef("String", nullable)
            return TypeRef("JSONValue", nullable)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return resolve(schema["allOf"][0], ctx, nested_name, nested)

    kind = schema.get("type")
    if isinstance(kind, list):  # OpenAPI 3.1 type arrays: ["string", "null"]
        nullable = "null" in kind
        rest = [k for k in kind if k != "null"]
        if len(rest) == 1:
            inner = resolve({**schema, "type": rest[0]}, ctx, nested_name, nested)
            return TypeRef(inner.swift, nullable)
        return TypeRef("JSONValue", nullable)

    if kind == "string":
        if "enum" in schema:
            nested.append(Nested(nested_name, [str(v) for v in schema["enum"]], schema.get("description")))
            return TypeRef(nested_name)
        fmt = schema.get("format")
        if fmt == "date":
            return TypeRef("LocalDate")
        if fmt == "time":
            return TypeRef("LocalTime")
        if fmt == "date-time":
            return TypeRef("Date")
        return TypeRef("String")
    if kind == "integer":
        return TypeRef("Int")
    if kind == "number":
        return TypeRef("Double")
    if kind == "boolean":
        return TypeRef("Bool")
    if kind == "array":
        item = resolve(schema.get("items", {}), ctx, singular(nested_name), nested)
        return TypeRef(f"[{item.swift}{'?' if item.nullable else ''}]")
    if kind == "object" or "additionalProperties" in schema:
        extra = schema.get("additionalProperties", True)
        if schema.get("properties"):
            ctx.notes.append(f"inline object with properties at {nested_name} -> JSONValue")
            return TypeRef("JSONValue")
        if extra is True or extra == {}:
            return TypeRef("[String: JSONValue]")
        if extra is False:
            return TypeRef("[String: JSONValue]")
        value = resolve(extra, ctx, nested_name + "Value", nested)
        return TypeRef(f"[String: {value.swift}{'?' if value.nullable else ''}]")
    # No type at all ("title" and "description" only): anything goes.
    return TypeRef("JSONValue", True)


def nested_type_name(prop: str, taken: set[str]) -> str:
    name = camel(prop, upper=True)
    if name in ("Type", "Protocol", "Self", "CodingKeys"):
        name += "Value"
    while name in taken:
        name += "Kind"
    return name


# --------------------------------------------------------------------------- models


def enum_decl(enum: Nested, indent: str) -> list[str]:
    i2 = indent + "    "
    i3 = i2 + "    "
    cases = []
    seen: set[str] = set()
    for value in enum.values:
        case = enum_case(value)
        while bare(case) in seen or bare(case) == "unknown":
            case = f"`{bare(case)}_`" if case.startswith("`") else case + "_"
        seen.add(bare(case))
        cases.append((case, value))
    lines = doc(enum.description, indent)
    lines.append(f"{indent}public enum {enum.name}: OpenEnum {{")
    for case, value in cases:
        lines.append(f"{i2}case {case}")
    lines.append(f"{i2}/// A value this build does not know (the server is newer than the app).")
    lines.append(f"{i2}case unknown(String)")
    lines.append("")
    lines.append(f"{i2}public static let allCases: [Self] = [{', '.join('.' + bare(c) for c, _ in cases)}]")
    lines.append("")
    lines.append(f"{i2}public init(rawValue: String) {{")
    lines.append(f"{i3}switch rawValue {{")
    for case, value in cases:
        lines.append(f"{i3}case {swift_string(value)}: self = .{case}")
    lines.append(f"{i3}default: self = .unknown(rawValue)")
    lines.append(f"{i3}}}")
    lines.append(f"{i2}}}")
    lines.append("")
    lines.append(f"{i2}public var rawValue: String {{")
    lines.append(f"{i3}switch self {{")
    for case, value in cases:
        lines.append(f"{i3}case .{case}: {swift_string(value)}")
    lines.append(f"{i3}case .unknown(let raw): raw")
    lines.append(f"{i3}}}")
    lines.append(f"{i2}}}")
    lines.append(f"{indent}}}")
    return lines


@dataclass
class Prop:
    wire: str
    name: str  # Swift identifier (maybe backticked)
    swift: str  # full declared type
    base: str  # type without Optional / Omittable
    mode: str  # required | nullable | optional | omittable
    description: str | None


def struct_decl(name: str, schema: dict, ctx: Context, request: bool) -> list[str]:
    nested: list[Nested] = []
    taken = set(ctx.names.values())
    required = set(schema.get("required", []))
    props: list[Prop] = []
    for wire, prop_schema in schema.get("properties", {}).items():
        nested_name = nested_type_name(wire, taken | {n.name for n in nested})
        ref = resolve(prop_schema, ctx, nested_name, nested)
        is_required = wire in required
        if is_required and not ref.nullable:
            mode, declared = "required", ref.swift
        elif is_required:
            mode, declared = "nullable", f"{ref.swift}?"
        elif request and ref.nullable:
            mode, declared = "omittable", f"Omittable<{ref.swift}>"
        else:
            mode, declared = "optional", f"{ref.swift}?"
        description = prop_schema.get("description")
        props.append(Prop(wire, ident(wire), declared, ref.swift, mode, description))

    lines = doc(schema.get("description"), "")
    if not schema.get("description"):
        lines.append(f"/// `{name}` from the API schema.")
    lines.append(f"public struct {ctx.names[name]}: Codable, Hashable, Sendable {{")
    for enum in nested:
        lines += enum_decl(enum, "    ")
        lines.append("")
    for p in props:
        lines += doc(p.description, "    ")
        lines.append(f"    public var {p.name}: {p.swift}")
    if props:
        lines.append("")

    # Memberwise init: required properties first in schema order, then the defaulted ones.
    params = []
    for p in sorted(props, key=lambda p: p.mode != "required"):
        if p.mode == "required":
            params.append(f"{p.name}: {p.swift}")
        elif p.mode == "omittable":
            params.append(f"{p.name}: {p.swift} = .omitted")
        else:
            params.append(f"{p.name}: {p.swift} = nil")
    if params:
        lines.append("    public init(")
        lines.append(",\n".join(f"        {param}" for param in params))
        lines.append("    ) {")
        for p in props:
            lines.append(f"        self.{bare(p.name)} = {p.name}")
        lines.append("    }")
    else:
        lines.append("    public init() {}")
    lines.append("")

    if props:
        lines.append("    private enum CodingKeys: String, CodingKey {")
        for p in props:
            if bare(p.name) == p.wire:
                lines.append(f"        case {p.name}")
            else:
                lines.append(f"        case {p.name} = {swift_string(p.wire)}")
        lines.append("    }")
        lines.append("")
        lines.append("    public init(from decoder: any Decoder) throws {")
        lines.append("        let container = try decoder.container(keyedBy: CodingKeys.self)")
        for p in props:
            key = f".{bare(p.name)}"
            target = f"self.{bare(p.name)}"
            if p.mode == "required":
                lines.append(f"        {target} = try container.decode({p.base}.self, forKey: {key})")
            elif p.mode == "omittable":
                lines.append(f"        {target} = try container.decodeOmittable({p.base}.self, forKey: {key})")
            else:
                lines.append(f"        {target} = try container.decodeIfPresent({p.base}.self, forKey: {key})")
        lines.append("    }")
        lines.append("")
        lines.append("    public func encode(to encoder: any Encoder) throws {")
        lines.append("        var container = encoder.container(keyedBy: CodingKeys.self)")
        for p in props:
            key = f".{bare(p.name)}"
            if p.mode in ("required", "nullable"):
                # A required nullable property is sent as an explicit null.
                lines.append(f"        try container.encode({p.name}, forKey: {key})")
            elif p.mode == "omittable":
                lines.append(f"        try container.encodeOmittable({p.name}, forKey: {key})")
            else:
                lines.append(f"        try container.encodeIfPresent({p.name}, forKey: {key})")
        lines.append("    }")
    else:
        lines.append("    public init(from decoder: any Decoder) throws {}")
        lines.append("    public func encode(to encoder: any Encoder) throws {")
        lines.append("        _ = encoder.container(keyedBy: AnyCodingKey.self)")
        lines.append("    }")
    lines.append("}")
    return lines


# --------------------------------------------------------------------------- operations


@dataclass
class Param:
    wire: str
    name: str
    swift: str  # declared parameter type
    base: str
    location: str  # path | query | header
    required: bool
    description: str | None
    is_array: bool


def response_type(op: dict, ctx: Context, nested_name: str, nested: list[Nested]) -> str:
    responses = op.get("responses", {})
    for status in sorted(responses):
        if not status.startswith("2"):
            continue
        if status == "204":
            return "NoContent"
        content = responses[status].get("content", {})
        body = content.get("application/json")
        if body is None:
            return "NoContent" if not content else "JSONValue"
        schema = body.get("schema", {})
        ref = resolve(schema, ctx, nested_name, nested)
        return f"{ref.swift}?" if ref.nullable and ref.swift != "JSONValue" else ref.swift
    return "NoContent"


def operations(ctx: Context) -> list[str]:
    groups: dict[str, list[tuple[str, str, dict]]] = {}
    for path, item in ctx.spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            tag = (op.get("tags") or ["misc"])[0]
            groups.setdefault(tag, []).append((path, method, op))

    lines = [
        "/// Every API operation, grouped by the server module (OpenAPI tag) it belongs to.",
        "///",
        "///     let lists = try await client.send(API.Reminders.reminderLists())",
        "///",
        "/// Each function only builds the request; `OrganizerClient.send` runs it.",
        "public enum API {",
    ]
    for tag in sorted(groups):
        group = camel(tag, upper=True)
        lines.append(f"    public enum {group} {{")
        for path, method, op in groups[tag]:
            op_id = op.get("operationId") or f"{method}_{path}"
            short = op_id[len(tag) + 1:] if op_id.startswith(tag + "_") else op_id
            func = camel(short)
            nested: list[Nested] = []
            params: list[Param] = []
            for raw in op.get("parameters", []):
                wire = raw["name"]
                if raw["in"] == "header" and wire.lower() in ("authorization", "x-author"):
                    continue  # the client sends the bearer token on every request
                if raw["in"] == "cookie":
                    continue
                schema = raw.get("schema", {})
                nested_name = camel(short, upper=True) + camel(wire, upper=True)
                ref = resolve(schema, ctx, nested_name, nested)
                base = ref.swift
                is_array = base.startswith("[")
                required = raw.get("required", False) or raw["in"] == "path"
                name = ident(wire.removeprefix("x-") if raw["in"] == "header" else wire)
                declared = base if required else f"{base}? = nil"
                params.append(Param(wire, name, declared, base, raw["in"], required,
                                    raw.get("description"), is_array))
            body_type = None
            body = op.get("requestBody", {}).get("content", {}).get("application/json")
            if body is not None:
                ref = resolve(body.get("schema", {}), ctx, camel(short, upper=True) + "Body", nested)
                body_type = ref.swift
            result = response_type(op, ctx, camel(short, upper=True) + "Response", nested)

            for enum in nested:
                lines += enum_decl(enum, "        ")
                lines.append("")
            lines.append(f"        /// `{method.upper()} {path}`")
            summary = op.get("description") or op.get("summary")
            if summary:
                lines.append("        ///")
                lines += doc(summary, "        ")
            documented = [p for p in params if p.description]
            if documented:
                lines.append("        ///")
                lines.append("        /// - Parameters:")
                for p in documented:
                    lines.append(f"        ///   - {bare(p.name)}: {p.description}")
            # Path parameters first, then the body, then query and header parameters.
            signature = [f"{p.name}: {p.swift}" for p in params if p.location == "path"]
            if body_type:
                signature.append(f"body: {body_type}")
            signature += [f"{p.name}: {p.swift}" for p in params if p.location != "path"]
            lines.append(f"        public static func {func}({', '.join(signature)}) -> Endpoint<{result}> {{")
            swift_path = path
            for p in params:
                if p.location == "path":
                    swift_path = swift_path.replace("{" + p.wire + "}", f"\\(Wire.segment({p.name}))")
            query = [p for p in params if p.location == "query"]
            headers = [p for p in params if p.location == "header"]
            args = [f"method: .{method}", f"path: \"{swift_path}\""]
            if query:
                items = ", ".join(f"({swift_string(p.wire)}, {p.name})" for p in query)
                args.append(f"query: Wire.query([{items}])")
            if headers:
                items = ", ".join(f"({swift_string(p.wire)}, {p.name})" for p in headers)
                args.append(f"headers: Wire.headers([{items}])")
            if body_type:
                args.append("body: body")
            lines.append(f"            Endpoint({', '.join(args)})")
            lines.append("        }")
            lines.append("")
        if lines[-1] == "":
            lines.pop()
        lines.append("    }")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return lines


# --------------------------------------------------------------------------- driver


def request_schema_names(spec: dict) -> set[str]:
    """Schemas reachable from a request body: their optional nullable fields are Omittable."""
    schemas = spec["components"]["schemas"]
    found: set[str] = set()

    def walk(node):
        if isinstance(node, dict):
            ref = node.get("$ref")
            if ref:
                name = ref.rsplit("/", 1)[-1]
                if name not in found:
                    found.add(name)
                    walk(schemas.get(name, {}))
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for item in spec["paths"].values():
        for op in item.values():
            if isinstance(op, dict) and "requestBody" in op:
                walk(op["requestBody"])
    return found


def response_schema_names(spec: dict) -> set[str]:
    schemas = spec["components"]["schemas"]
    found: set[str] = set()

    def walk(node):
        if isinstance(node, dict):
            ref = node.get("$ref")
            if ref:
                name = ref.rsplit("/", 1)[-1]
                if name not in found:
                    found.add(name)
                    walk(schemas.get(name, {}))
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for item in spec["paths"].values():
        for op in item.values():
            if isinstance(op, dict):
                walk(op.get("responses", {}))
    return found


def main() -> int:
    spec_path = Path(sys.argv[1]) if len(sys.argv) > 1 else SPEC
    spec = json.loads(spec_path.read_text())
    schemas = spec["components"]["schemas"]

    names = {}
    for name in schemas:
        swift = camel(name, upper=True) if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name) else name
        if swift in RESERVED_TYPE_NAMES:
            print(f"note: schema {name} is generated as API{swift} (the name is reserved)")
            swift = "API" + swift
        names[name] = swift

    request = request_schema_names(spec)
    both = request & response_schema_names(spec)
    for name in sorted(both):
        print(f"note: {name} is both a request body and a response; its optional nullable fields are Omittable")
    ctx = Context(spec, names, request)

    models = [HEADER, "import Foundation", ""]
    for name in sorted(schemas, key=lambda n: names[n]):
        models += struct_decl(name, schemas[name], ctx, name in request)
        models.append("")
    ops = [HEADER, "import Foundation", ""] + operations(ctx) + [""]

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "Models.swift").write_text("\n".join(models))
    (OUT / "Operations.swift").write_text("\n".join(ops))
    for note in ctx.notes:
        print("note:", note)
    count = sum(1 for item in spec["paths"].values() for m in item if m in ("get", "post", "put", "patch", "delete"))
    print(f"wrote {len(schemas)} models and {count} operations to {OUT.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
